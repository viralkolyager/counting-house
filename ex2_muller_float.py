"""Упражнение №2. Последовательность Мюллера во float.

а) Программа, которая выводит x30.
б) Аналитический предел последовательности.
в) Почему получается 100.

Ответы на (б) и (в) — в docstring ниже и в README.md.

б) Неподвижные точки x = f(x, x) — корни уравнения
       x^3 - 108 x^2 + 815 x - 1500 = (x - 3)(x - 5)(x - 100) = 0.
   Подстановка x_n = u_{n+1} / u_n превращает рекурсию в линейную:
       u_{n+1} = 108 u_n - 815 u_{n-1} + 1500 u_{n-2},
   общее решение u_n = a*3^n + b*5^n + c*100^n.
   При x0 = 4, x1 = 4.25 получаем a = b, c = 0, т.е.
       x_n = (3^(n+1) + 5^(n+1)) / (3^n + 5^n)  ->  5   при n -> бесконечности.
   (В тексте курса сказано «должно было получиться 4» — это опечатка:
   4 — лишь начальное значение x0, а предел равен 5.)

в) Коэффициент c при 100^n точно равен нулю только в точной арифметике.
   Уже 4.25 и 1500/z округляются в binary64, и в решении появляется
   паразитная составляющая c ≈ 1e-17 * 100^n. Она растёт в (100/5)^n = 20^n
   раз быстрее «правильной» и примерно к n ≈ 12–15 начинает доминировать.
   Точка 100 — притягивающая для рекурсии, а 5 — отталкивающая,
   поэтому любая погрешность округления уводит последовательность к 100.
"""
from muller import exact, sequence

N = 30


def main() -> None:
    xs = sequence(4.0, 4.25, N)
    print(f"{'n':>3} {'float':>24} {'точно':>24}")
    for n, x in enumerate(xs):
        print(f"{n:>3} {x:>24.17g} {float(exact(n)):>24.17g}")
    print()
    print(f"а) x{N} во float  = {xs[N]!r}")
    print(f"б) предел        = 5   (точное x{N} = {float(exact(N))!r})")
    print("в) см. docstring этого файла: ошибка округления раздувается в 20^n раз")


if __name__ == "__main__":
    main()
